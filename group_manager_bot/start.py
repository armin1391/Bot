# =========================================================
# 🚀 پردازش /start و دکمه‌ها
# =========================================================

def handle_start(
    message,
    send_message
):

    chat = message.get(
        "chat",
        {}
    )

    chat_id = chat.get(
        "id"
    )

    if chat_id is None:
        return False

    text = message.get(
        "text"
    )

    if text == "/start":

        send_message(
            chat_id,
            WELCOME_TEXT,
            components=main_keyboard()
        )

        return True

    if text == "➕ افزودن ربات به گروه":

        send_message(
            chat_id,
            ADD_GROUP_TEXT,
            components=back_keyboard()
        )

        return True

    if text == "📖 راهنما":

        send_message(
            chat_id,
            HELP_TEXT,
            components=back_keyboard()
        )

        return True

    if text == "🛟 پشتیبانی":

        send_message(
            chat_id,
            SUPPORT_TEXT,
            components=back_keyboard()
        )

        return True

    if text == "🔙 بازگشت":

        send_message(
            chat_id,
            WELCOME_TEXT,
            components=main_keyboard()
        )

        return True

    return False